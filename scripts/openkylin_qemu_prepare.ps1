param(
    [string]$Iso = "runs/openkylin-validation-20260902/media/openKylin-Desktop-V2.0-SP2-20260813-x86_64.iso",
    [string]$VmDir = "runs/openkylin-validation-20260902/qemu-x86_64",
    [int]$DiskSizeGb = 40
)

$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root
$vmPath = Join-Path $root $VmDir
$isoPath = Join-Path $root $Iso
$qemu = "C:\Program Files\qemu\qemu-system-x86_64.exe"
$qemuImg = "C:\Program Files\qemu\qemu-img.exe"
if (-not (Test-Path $qemu)) { $qemu = (Get-Command qemu-system-x86_64 -ErrorAction SilentlyContinue).Source }
if (-not (Test-Path $qemuImg)) { $qemuImg = (Get-Command qemu-img -ErrorAction SilentlyContinue).Source }
if (-not $qemu -or -not (Test-Path $qemu)) { throw "qemu-system-x86_64.exe not found" }
if (-not $qemuImg -or -not (Test-Path $qemuImg)) { throw "qemu-img.exe not found" }
if (-not (Test-Path $isoPath)) { throw "ISO not found: $isoPath" }
New-Item -ItemType Directory -Force -Path $vmPath | Out-Null
$disk = Join-Path $vmPath "openkylin.qcow2"
if (-not (Test-Path $disk)) {
    & $qemuImg create -f qcow2 $disk ("{0}G" -f $DiskSizeGb) | Tee-Object -FilePath (Join-Path $vmPath "qemu-img.log")
    if ($LASTEXITCODE -ne 0) { throw "qemu-img failed with exit code $LASTEXITCODE" }
}
$linkRoot = "C:\kmb-openkylin-validation"
$vmLink = Join-Path $linkRoot "vm"
$mediaLink = Join-Path $linkRoot "media"
New-Item -ItemType Directory -Force -Path $linkRoot | Out-Null
foreach ($link in @(@($vmLink, $vmPath), @($mediaLink, (Split-Path -Parent $isoPath)))) {
    if (-not (Test-Path $link[0])) { New-Item -ItemType Junction -Path $link[0] -Target $link[1] | Out-Null }
}
$asciiDisk = Join-Path $vmLink "openkylin.qcow2"
$asciiIso = Join-Path $mediaLink (Split-Path -Leaf $isoPath)
$asciiSerial = Join-Path $vmLink "serial.log"
$asciiMonitor = Join-Path $vmLink "monitor.log"
$launch = @"
# Generated by openkylin_qemu_prepare.ps1. Review before execution.
& "$qemu" -name openkylin-validation -machine q35 -m 4096 -smp 4 `
  -accel whpx `
  -drive "file=$asciiDisk,if=virtio,format=qcow2" `
  -cdrom "$asciiIso" -boot order=d `
  -nic user,model=virtio-net-pci `
  -serial "file:$asciiSerial" `
  -display none -monitor "file:$asciiMonitor"
"@
$launchPath = Join-Path $vmPath "launch-qemu.ps1"
Set-Content -Path $launchPath -Value $launch -Encoding ASCII
@{
    prepared_at = (Get-Date).ToUniversalTime().ToString("o")
    qemu = $qemu
    qemu_img = $qemuImg
    iso = $isoPath
    disk = $disk
    disk_size_gb = $DiskSizeGb
    launch_script = $launchPath
    ascii_junction_root = $linkRoot
    isolation = "dedicated qcow2 under runs/openkylin-validation-20260902; no host disks or boot configuration"
} | ConvertTo-Json | Set-Content -Path (Join-Path $vmPath "vm-metadata.json") -Encoding UTF8
Write-Output "QEMU VM prepared: $vmPath"
Write-Output "Launch script: $launchPath"
